export const LANGUES_BOT = Object.keys(TEXTES)

// Texte d'une clé dans la langue du contact, avec remplacement des {variables}
export function tx(langue, cle, valeurs = {}) {
  const table = TEXTES[langue] ?? TEXTES.fr
  let s = table[cle] ?? TEXTES.fr[cle] ?? ''
  const tout = { societe: process.env.COMPANY_NAME ?? 'GREENFIELD', ...valeurs }
  for (const [k, v] of Object.entries(tout)) s = s.split(`{${k}}`).join(String(v ?? ''))
  return s
}

export function localeDe(langue) {
  return (TEXTES[langue] ?? TEXTES.fr).locale
}
