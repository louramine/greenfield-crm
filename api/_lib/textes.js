// Textes fixes du chatbot (boutons, fiches terrain, confirmations) dans les langues des contacts.
// fr : français, en : anglais, ar : arabe, dar : darija en lettres latines, dar_ar : darija en lettres arabes.
// Les messages de conversation libre sont rédigés par Claude, ils ne passent pas par ce fichier.

const N = (v) => String(v ?? '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()

// Langue du contact : d'abord celle repérée dans la conversation, sinon celle de sa fiche CRM
export function langueDe(conv, acheteur) {
  const s = N(conv?.langue ? conv.langue : conv?.fiche?.langue)
  if (s.includes('darija')) return s.includes('latin') ? 'dar' : 'dar_ar'
  if (s.includes('angl')) return 'en'
  if (s.includes('engl')) return 'en'
  if (s.includes('arab')) return 'ar'
  if (s.includes('fran')) return 'fr'
  const crm = N(conv?.fiche?.langue_crm ? conv.fiche.langue_crm : acheteur?.langue)
  if (crm.startsWith('angl')) return 'en'
  if (crm.startsWith('arab')) return 'ar'
  if (crm.startsWith('darija')) return 'dar'
  return 'fr'
}

