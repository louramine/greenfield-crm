create temp table gf_m (n int primary key, id text unique);
create temp table gf_report (ord int, libelle text, valeur text);

do $$
declare
  p int;
  l record;
  cand text;
  nb_new int;
begin
  for p in 1..6 loop
    for l in select * from gf_l where n not in (select n from gf_m) order by n loop
      select t.id::text into cand
        from public.terrains t
       where t.id::text not in (select id from gf_m)
         and case p
           when 1 then coalesce(t.superficie, 0)::numeric = coalesce(l.sup, 0)
                   and pg_temp.gf_nz(t.tf) <> '' and pg_temp.gf_nz(t.tf) = pg_temp.gf_nz(l.tf)
                   and pg_temp.gf_nz(t.urba) = pg_temp.gf_nz(l.urba)
           when 2 then coalesce(t.superficie, 0)::numeric = coalesce(l.sup, 0)
                   and pg_temp.gf_nz(t.tf) <> '' and pg_temp.gf_nz(t.tf) = pg_temp.gf_nz(l.tf)
           when 3 then coalesce(t.superficie, 0)::numeric = coalesce(l.sup, 0)
                   and pg_temp.gf_nz(t.urba) = pg_temp.gf_nz(l.urba)
                   and pg_temp.gf_nz(coalesce(t.localisation_origine, t.localisation, t.quartier)) = pg_temp.gf_nz(l.quartier)
           when 4 then pg_temp.gf_nz(t.tf) <> '' and pg_temp.gf_nz(t.tf) = pg_temp.gf_nz(l.tf)
                   and pg_temp.gf_nz(t.urba) = pg_temp.gf_nz(l.urba)
                   and pg_temp.gf_nz(coalesce(t.localisation_origine, t.localisation, t.quartier)) = pg_temp.gf_nz(l.quartier)
           when 5 then t.id::text = l.n::text
                   and (coalesce(t.superficie, 0)::numeric = coalesce(l.sup, 0)
                        or pg_temp.gf_nz(t.urba) = pg_temp.gf_nz(l.urba)
                        or pg_temp.gf_nz(coalesce(t.localisation_origine, t.localisation, t.quartier)) = pg_temp.gf_nz(l.quartier))
           else coalesce(t.superficie, 0)::numeric = coalesce(l.sup, 0)
                   and pg_temp.gf_nz(coalesce(t.localisation_origine, t.localisation, t.quartier)) = pg_temp.gf_nz(l.quartier)
         end
       order by (t.id::text = l.n::text) desc, t.id
       limit 1;
      if cand is not null then
        insert into gf_m values (l.n, cand);
      end if;
    end loop;
  end loop;

  select count(*) into nb_new from gf_l where n not in (select n from gf_m);
  if nb_new > 12 then
    raise exception 'Rapprochement douteux : % lignes du listing sans terrain correspondant. Rien n a ete modifie, envoyez ce message a Claude.', nb_new;
  end if;
end $$;

