  with check (public.mon_role() is not null and cree_par = public.mon_nom());
create policy "liens_modif" on public.carte_liens for update to authenticated
  using (public.mon_role() in ('admin', 'associe') or cree_par = public.mon_nom())
  with check (public.mon_role() in ('admin', 'associe') or cree_par = public.mon_nom());
revoke all on public.carte_liens from anon;
grant select, insert, update on public.carte_liens to authenticated;

-- ─── 3. Sélections envoyées par les prospects ────────────────────────────────────
