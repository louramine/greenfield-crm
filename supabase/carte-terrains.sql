-- ─── 1. Contours CADGIS (un enregistrement par titre ou réquisition) ───────────────
-- cle : 'T' ou 'R' + numéro + '/' + indice, par exemple T22853/33 ou R7123/C,
--       ou la référence du terrain (GF-26-0936) pour un contour rattaché directement à un terrain
-- geom : contour exact (liste d'anneaux [lat, lng]) ; geom_approx : forme volontairement approximative
create table if not exists public.terrain_contours (
  cle text primary key,
  surface_plan numeric,
  geom jsonb not null,
  geom_approx jsonb not null,
  lat double precision,
  lng double precision,
  lat_approx double precision,
  lng_approx double precision,
  importe_le timestamptz not null default now()
);

alter table public.terrain_contours enable row level security;
drop policy if exists "contours_lecture" on public.terrain_contours;
drop policy if exists "contours_import" on public.terrain_contours;
create policy "contours_lecture" on public.terrain_contours for select to authenticated
  using (public.mon_role() is not null);
create policy "contours_import" on public.terrain_contours for all to authenticated
  using (public.mon_role() = 'admin') with check (public.mon_role() = 'admin');
revoke all on public.terrain_contours from anon;
grant select, insert, update, delete on public.terrain_contours to authenticated;

-- Clés de titres contenues dans un texte libre : '28536/53 - 28562/53' donne {T28536/53, T28562/53}
create or replace function public.tf_cles(p text) returns text[]
language sql immutable as $$
  select coalesce(array_agg(distinct
           (case when m[1] is not null and m[1] <> '' then 'R' else 'T' end) || ltrim(m[2], '0') || '/' || upper(m[3])), '{}')
  from regexp_matches(coalesce(p, ''), '(\mR\s*\.?\s*)?([0-9]{2,7})\s*/\s*([A-Za-z0-9]+)', 'gi') as m
$$;

-- Coordonnées d'un lien Google Maps (dernier repère !3d...!4d..., sinon @lat,lng ou q=lat,lng)
create or replace function public.gm_coords(p text) returns double precision[]
language sql immutable as $$
  select case
    when p ~ '!3d-?[0-9.]+!4d-?[0-9.]+' then (regexp_match(p, '.*!3d(-?[0-9.]+)!4d(-?[0-9.]+)'))::double precision[]
    when p ~ '@-?[0-9]+\.[0-9]+,-?[0-9]+\.[0-9]+' then (regexp_match(p, '@(-?[0-9]+\.[0-9]+),(-?[0-9]+\.[0-9]+)'))::double precision[]
    when p ~ '[?&]q=-?[0-9]+\.[0-9]+,-?[0-9]+\.[0-9]+' then (regexp_match(p, '[?&]q=(-?[0-9]+\.[0-9]+),(-?[0-9]+\.[0-9]+)'))::double precision[]
    else null end
$$;

-- Contours des terrains visibles par l'utilisateur connecté (les droits sur terrains s'appliquent)
-- Un contour est rattaché par le TF. A défaut de contour pour le TF, on prend le contour enregistré
-- sous la référence du terrain (cle = GF-26-0936) : parcelle retrouvée par position ou dessin de l'ancienne carte MyMaps.
create or replace function public.carte_contours()
returns table (terrain_id bigint, cle text, surface_plan numeric, geom jsonb, geom_approx jsonb,
               lat double precision, lng double precision, lat_approx double precision, lng_approx double precision)
language sql stable security invoker set search_path = public as $$
  select t.id, c.cle, c.surface_plan, c.geom, c.geom_approx, c.lat, c.lng, c.lat_approx, c.lng_approx
  from public.terrains t
  cross join lateral unnest(public.tf_cles(t.tf)) as k(cle)
  join public.terrain_contours c on c.cle = k.cle
  union all
  select t.id, c.cle, c.surface_plan, c.geom, c.geom_approx, c.lat, c.lng, c.lat_approx, c.lng_approx
  from public.terrains t
  join public.terrain_contours c on c.cle = t.ref
  where not exists (select 1 from public.terrain_contours c2 where c2.cle = any(public.tf_cles(t.tf)))
$$;
grant execute on function public.carte_contours() to authenticated;

-- ─── 2. Liens temporaires ───────────────────────────────────────────────────
create table if not exists public.carte_liens (
  id bigint generated by default as identity primary key,
  token text not null unique default encode(gen_random_bytes(16), 'hex'),
  version text not null check (version in ('decouverte', 'qualifie')),
  terrain_ids bigint[],            -- null : tous les terrains au statut Disponible
  prospect text,
  acheteur_id bigint,
  note text,
  expire_le timestamptz not null,
  revoque boolean not null default false,
  cree_par text default public.mon_nom(),
  cree_le timestamptz not null default now(),
  vues integer not null default 0,
  premiere_vue timestamptz,
  derniere_vue timestamptz
);
create index if not exists carte_liens_cree_le on public.carte_liens (cree_le desc);
-- Chaque nouveau lien est rattaché à un promoteur (les liens de test déjà créés sans promoteur restent valables)
do $$ begin
  alter table public.carte_liens add constraint carte_liens_acheteur_requis check (acheteur_id is not null) not valid;
exception when duplicate_object then null;
end $$;

alter table public.carte_liens enable row level security;
drop policy if exists "liens_lecture" on public.carte_liens;
drop policy if exists "liens_creation" on public.carte_liens;
drop policy if exists "liens_modif" on public.carte_liens;
-- Toute l'équipe crée des liens ; les sourceurs ne voient et ne gèrent que les leurs
create policy "liens_lecture" on public.carte_liens for select to authenticated
  using (public.mon_role() in ('admin', 'associe') or cree_par = public.mon_nom());
