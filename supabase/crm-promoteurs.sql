-- Greenfield CRM : fiche promoteur enrichie, suivi des échanges et import de la base promoteurs
-- A exécuter une seule fois dans Supabase (SQL Editor > New query > coller > Run).
-- Sans danger : le script ajoute des colonnes et des tables, il ne supprime et ne modifie aucune donnée existante.
-- Il peut être relancé : un promoteur déjà présent (même numéro) n'est pas recréé.

-- 1. Fiche promoteur : identité, critères de recherche, suivi
alter table public.acheteurs add column if not exists societe text;
alter table public.acheteurs add column if not exists telephone text;
alter table public.acheteurs add column if not exists email text;
alter table public.acheteurs add column if not exists fonction text;
alter table public.acheteurs add column if not exists langue text;
alter table public.acheteurs add column if not exists source text;
alter table public.acheteurs add column if not exists notes text;
alter table public.acheteurs add column if not exists typologies text[] not null default '{}';
alter table public.acheteurs add column if not exists zonages text[] not null default '{}';
alter table public.acheteurs add column if not exists quartiers text[] not null default '{}';
alter table public.acheteurs add column if not exists sup_min numeric;
alter table public.acheteurs add column if not exists sup_max numeric;
alter table public.acheteurs add column if not exists prix_m2_max numeric;
alter table public.acheteurs add column if not exists horizon text;
alter table public.acheteurs add column if not exists mode_acquisition text;
alter table public.acheteurs add column if not exists whatsapp_consentement text not null default 'À confirmer';
alter table public.acheteurs add column if not exists whatsapp_stop boolean not null default false;
alter table public.acheteurs add column if not exists derniere_interaction timestamptz;
alter table public.acheteurs add column if not exists prochaine_relance date;
alter table public.acheteurs add column if not exists created_at timestamptz not null default now();
create unique index if not exists acheteurs_telephone_unique on public.acheteurs (telephone) where telephone is not null;

-- 2. Les échanges (appels, rendez-vous, WhatsApp) peuvent être rattachés à une fiche promoteur
alter table public.interactions add column if not exists acheteur_id bigint references public.acheteurs(id) on delete set null;
alter table public.interactions add column if not exists canal text;
create index if not exists interactions_acheteur_idx on public.interactions (acheteur_id);

-- 3. Historique WhatsApp (rempli par le chatbot et par les envois depuis le CRM)
create table if not exists public.whatsapp_messages (
  id            bigint generated by default as identity primary key,
  acheteur_id   bigint references public.acheteurs(id) on delete set null,
  telephone     text not null,
  direction     text not null check (direction in ('entrant', 'sortant')),
  type          text,
  contenu       text,
  action        text,
  terrain_id    bigint,
  auteur        text,
  wa_message_id text,
  created_at    timestamptz not null default now()
);
create index if not exists whatsapp_messages_acheteur_idx on public.whatsapp_messages (acheteur_id, created_at desc);
create index if not exists whatsapp_messages_tel_idx on public.whatsapp_messages (telephone, created_at desc);

-- 4. Réponse de chaque promoteur pour chaque terrain proposé (base des préférences apprises)
create table if not exists public.acheteur_terrain_reponses (
  id               bigint generated by default as identity primary key,
  acheteur_id      bigint not null references public.acheteurs(id) on delete cascade,
  terrain_id       bigint not null,
  statut           text not null default 'envoye',
  raison_refus     text,
  creneau_visite   text,
  teaser_envoye_le timestamptz,
  updated_at       timestamptz not null default now(),
  unique (acheteur_id, terrain_id)
);
alter table public.acheteur_terrain_reponses add column if not exists canal text;
alter table public.acheteur_terrain_reponses add column if not exists envoye_par text;
alter table public.acheteur_terrain_reponses add column if not exists notes text;

-- 5. Droits : toute l'équipe connectée lit et enregistre, seul un admin supprime.
--    Le chatbot écrit avec la clé serveur, qui n'est pas concernée par ces règles.
alter table public.whatsapp_messages enable row level security;
alter table public.acheteur_terrain_reponses enable row level security;

drop policy if exists "equipe lit messages" on public.whatsapp_messages;
drop policy if exists "equipe ecrit messages" on public.whatsapp_messages;
drop policy if exists "admin supprime messages" on public.whatsapp_messages;
create policy "equipe lit messages" on public.whatsapp_messages for select to authenticated using (public.mon_role() is not null);
create policy "equipe ecrit messages" on public.whatsapp_messages for insert to authenticated with check (public.mon_role() is not null);
create policy "admin supprime messages" on public.whatsapp_messages for delete to authenticated using (public.mon_role() = 'admin');

drop policy if exists "equipe lit reponses" on public.acheteur_terrain_reponses;
drop policy if exists "equipe ajoute reponses" on public.acheteur_terrain_reponses;
drop policy if exists "equipe modifie reponses" on public.acheteur_terrain_reponses;
drop policy if exists "admin supprime reponses" on public.acheteur_terrain_reponses;
create policy "equipe lit reponses" on public.acheteur_terrain_reponses for select to authenticated using (public.mon_role() is not null);
create policy "equipe ajoute reponses" on public.acheteur_terrain_reponses for insert to authenticated with check (public.mon_role() is not null);
create policy "equipe modifie reponses" on public.acheteur_terrain_reponses for update to authenticated using (public.mon_role() is not null) with check (public.mon_role() is not null);
create policy "admin supprime reponses" on public.acheteur_terrain_reponses for delete to authenticated using (public.mon_role() = 'admin');

