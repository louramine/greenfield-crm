-- Greenfield CRM : fiche demande (terrains proposés et historique des modifications)
-- A exécuter une fois dans Supabase (SQL Editor > New query > coller > Run), après demandes-equipe.sql.
-- Relançable sans effet de bord.
-- Chaque membre de l'équipe voit et modifie les terrains proposés et l'historique des demandes qu'il peut voir
-- (les siennes et celles attribuées à toute l'équipe ; les admins voient tout).

-- Date de création des deals et demandes (déjà présente en général)
alter table public.deals add column if not exists created_at timestamptz default now();

create table if not exists public.demande_terrains (
  id bigint generated by default as identity primary key,
  deal_id bigint not null references public.deals(id) on delete cascade,
  terrain_id bigint,
  terrain_label text,
  propose_par text,
  created_at timestamptz not null default now(),
  unique (deal_id, terrain_id)
);

create table if not exists public.demande_historique (
  id bigint generated by default as identity primary key,
  deal_id bigint not null references public.deals(id) on delete cascade,
  auteur text,
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);
create index if not exists demande_historique_deal on public.demande_historique (deal_id, created_at desc);

alter table public.demande_terrains enable row level security;
alter table public.demande_historique enable row level security;

drop policy if exists "demande_terrains_equipe" on public.demande_terrains;
create policy "demande_terrains_equipe" on public.demande_terrains for all to authenticated
  using (public.mon_role() is not null and exists (select 1 from public.deals d where d.id = deal_id))
  with check (public.mon_role() is not null and exists (select 1 from public.deals d where d.id = deal_id));

-- L'historique se lit et s'enrichit, il ne se modifie pas et ne s'efface pas
drop policy if exists "demande_historique_lecture" on public.demande_historique;
drop policy if exists "demande_historique_ajout" on public.demande_historique;
create policy "demande_historique_lecture" on public.demande_historique for select to authenticated
  using (public.mon_role() is not null and exists (select 1 from public.deals d where d.id = deal_id));
create policy "demande_historique_ajout" on public.demande_historique for insert to authenticated
  with check (public.mon_role() is not null and auteur = public.mon_nom() and exists (select 1 from public.deals d where d.id = deal_id));

-- Recharge le schéma de l'API pour que les nouvelles tables soient visibles tout de suite
notify pgrst, 'reload schema';
