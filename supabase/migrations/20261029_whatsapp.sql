-- Greenfield CRM : intégration WhatsApp
-- A exécuter une seule fois dans Supabase (SQL Editor > New query > Run).
-- Le script est sans danger : il n'ajoute que des colonnes et des tables, il ne supprime rien.

-- 1. Coordonnées et préférences WhatsApp sur la fiche acheteur
alter table public.acheteurs add column if not exists telephone text;
alter table public.acheteurs add column if not exists whatsapp_stop boolean not null default false;
alter table public.acheteurs add column if not exists derniere_interaction timestamptz;
alter table public.acheteurs add column if not exists source text;
alter table public.acheteurs add column if not exists notes text;
create unique index if not exists acheteurs_telephone_unique on public.acheteurs (telephone) where telephone is not null;

-- 2. Historique complet des conversations
create table if not exists public.whatsapp_messages (
  id            bigint generated by default as identity primary key,
  acheteur_id   bigint references public.acheteurs(id) on delete set null,
  telephone     text not null,
  direction     text not null check (direction in ('entrant', 'sortant')),
  type          text,
  contenu       text,
  action        text,
  terrain_id    bigint,
  auteur        text,
  wa_message_id text,
  created_at    timestamptz not null default now()
);
create index if not exists whatsapp_messages_acheteur_idx on public.whatsapp_messages (acheteur_id, created_at desc);
create index if not exists whatsapp_messages_tel_idx on public.whatsapp_messages (telephone, created_at desc);

-- 3. Réponse de chaque acheteur pour chaque terrain proposé
create table if not exists public.acheteur_terrain_reponses (
  id              bigint generated by default as identity primary key,
  acheteur_id     bigint not null references public.acheteurs(id) on delete cascade,
  terrain_id      bigint not null,
  statut          text not null default 'envoye',
  raison_refus    text,
  creneau_visite  text,
  teaser_envoye_le timestamptz,
  updated_at      timestamptz not null default now(),
  unique (acheteur_id, terrain_id)
);

-- 4. Droits : l'équipe connectée lit tout, seul le serveur (clé service) écrit
alter table public.whatsapp_messages enable row level security;
alter table public.acheteur_terrain_reponses enable row level security;

drop policy if exists "equipe lit messages" on public.whatsapp_messages;
create policy "equipe lit messages" on public.whatsapp_messages
  for select to authenticated using (true);

drop policy if exists "equipe lit reponses" on public.acheteur_terrain_reponses;
create policy "equipe lit reponses" on public.acheteur_terrain_reponses
  for select to authenticated using (true);
