update public.terrains
   set localisation = regexp_replace(trim(localisation), '\s+', ' ', 'g')
 where localisation is not null and localisation <> regexp_replace(trim(localisation), '\s+', ' ', 'g');

-- Reference unique par terrain
create sequence if not exists public.terrains_ref_seq;

update public.terrains t
   set ref = 'GF-' || lpad((s.rn + s.base)::text, 4, '0')
  from (
    select id,
           row_number() over (order by id) as rn,
           (select coalesce(max(substring(ref from 4)::int), 0) from public.terrains where ref ~ '^GF-[0-9]+$') as base
      from public.terrains where ref is null
  ) s
 where t.id = s.id;

select setval('public.terrains_ref_seq',
              greatest((select coalesce(max(substring(ref from 4)::int), 0) from public.terrains where ref ~ '^GF-[0-9]+$'), 1),
              (select count(*) > 0 from public.terrains where ref is not null));

alter table public.terrains
  alter column ref set default 'GF-' || lpad(nextval('public.terrains_ref_seq')::text, 4, '0');
create unique index if not exists terrains_ref_uniq on public.terrains (ref);
grant usage on sequence public.terrains_ref_seq to authenticated;
